#!/usr/bin/env python3
"""Check ownership headers, attribution links, and accidental comment residue.

This is a source-only test for the CartPole web demo, not a legal rights audit.
Project author: Alysha Pursley.
Run: python3 -S web-demo/tests/attribution-check.py
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "web-demo"
ORIGINAL = ROOT.parent / "Original"
issues = []

def check():
    sources = [*WEB.rglob("*.js"), *WEB.rglob("*.mjs"), *WEB.rglob("*.css"),
               *WEB.rglob("*.html"), *WEB.rglob("*.py"), *ORIGINAL.rglob("*.py")]
    for file in sources:
        content = file.read_text(encoding="utf-8")
        head = content[:850]
        prefix = head.removeprefix("#!/usr/bin/env python3").lstrip()
        if file.suffix == ".html" and not (prefix.startswith("<!--") or re.match(r"(?i)<!doctype html>\s*<!--", prefix)):
            issues.append(f"{file.relative_to(ROOT)}: missing HTML header")
        elif file.suffix in (".js", ".mjs", ".css") and not prefix.startswith("/*"):
            issues.append(f"{file.relative_to(ROOT)}: missing multiline header")
        elif file.suffix == ".py" and not (prefix.startswith(chr(34) * 3) or (prefix.startswith("#") and '"""' in head)):
            issues.append(f"{file.relative_to(ROOT)}: missing Python module docstring")
        if "Alysha Pursley" not in head:
            issues.append(f"{file.relative_to(ROOT)}: maintainer absent from header")
        if re.search(r"(?i)\\b(chatgpt|claude|written by an ai|generated by an ai|you asked me|the user requested)\\b", content):
            issues.append(f"{file.relative_to(ROOT)}: possible assistant residue")
        if re.search(r"(?i)\\b(TODO|FIXME|HACK|XXX)\\b", content):
            issues.append(f"{file.relative_to(ROOT)}: unresolved maintenance marker")
    notices = ORIGINAL / "docs/third-party-notices.md"
    for name in ("Grzegorz Surma", "Farama", "MIT"):
        if name not in notices.read_text(encoding="utf-8"):
            issues.append(f"third-party notice missing: {name}")
    for filename in ("config.js", "dqn-agent.js", "cartpole-env.js"):
        file = WEB / "assets/js" / filename
        content = file.read_text(encoding="utf-8")
        for path in re.findall(r"License (?:details|and attribution details):\\s*([^\\s*]+)", content):
            if (file.parent / path.rstrip(".")).resolve() != notices.resolve():
                issues.append(f"{filename}: broken notice path {path}")
    if issues:
        for issue in issues:
            print("FAIL:", issue, file=sys.stderr)
        return 1
    print(f"Attribution source checks passed: {len(sources)} project source files; notices retained.")
    return 0

if __name__ == "__main__":
    raise SystemExit(check())
